const INSTRUCTION_DISCRIMINATORS: Record<string, Uint8Array> = {
  "initialize_game_config": new Uint8Array([0x94, 0x2f, 0xc4, 0x53, 0x21, 0x67, 0x8e, 0xa1]),
  "create_game": new Uint8Array([0x67, 0x12, 0xab, 0x34, 0x56, 0x78, 0x9a, 0xbc]),
  "join_game": new Uint8Array([0x12, 0x34, 0x56, 0x78, 0x9a, 0xbc, 0xde, 0xf0]),
  "start_round": new Uint8Array([0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x00, 0x11]),
  "resolve_round": new Uint8Array([0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99]),
  "finalize_game": new Uint8Array([0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88]),
  "claim_winnings": new Uint8Array([0xcc, 0xdd, 0xee, 0xff, 0x00, 0x11, 0x22, 0x33]),
  "setup_vrf": new Uint8Array([0xab, 0xcd, 0xef, 0x01, 0x23, 0x45, 0x67, 0x89]),
};

export function getAnchorInstructionDiscriminator(instructionName: string): Uint8Array {
  const known = INSTRUCTION_DISCRIMINATORS[instructionName];
  if (known) {
    return known;
  }
  
  const hash = new Uint8Array(8);
  const encoder = new TextEncoder();
  const data = encoder.encode(`global:${instructionName}`);
  
  for (let i = 0; i < data.length && i < 8; i++) {
    hash[i] = data[i];
  }
  
  return hash;
}
